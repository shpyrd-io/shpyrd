import { afterEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import type { Project } from "@/api/types";
import type { Perms } from "@/lib/perms";
import seed from "../../../mock/projects.json";
import { Config } from "./config";
const fake = vi.hoisted(() => ({ configVars: vi.fn(), changeConfigVars: vi.fn() }));
vi.mock("@/api/api", () => ({ api: fake }));
let queries: QueryClient;
afterEach(() => { cleanup(); queries?.clear(); vi.resetAllMocks(); });
it("shows variables but only offers replacement for saved secrets", async () => {
  const answer = { vars: [{ name: "PASSWORD" }], variables: [{ name: "APP_URL", value: "https://example.test" }], pending: false };
  fake.configVars.mockResolvedValue(answer);
  fake.changeConfigVars.mockResolvedValue(answer);
  queries = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const project = seed[0] as unknown as Project;
  render(<QueryClientProvider client={queries}><Config project={project} perms={{ config: true } as Perms} /></QueryClientProvider>);
  expect(await screen.findByText("https://example.test")).toBeTruthy();
  expect(screen.queryByRole("button", { name: "Make variable" })).toBeNull();
  expect(screen.getByRole("button", { name: "Make secret" })).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Replace" }));
  const input = screen.getByLabelText("New value for PASSWORD") as HTMLInputElement;
  expect(input.value).toBe("");
  expect(input.type).toBe("password");
  fireEvent.change(input, { target: { value: "replacement" } });
  fireEvent.submit(input.closest("form")!);
  await waitFor(() => expect(fake.changeConfigVars).toHaveBeenCalledWith(project.slug, { kind: "secret", set: { PASSWORD: "replacement" } }));
});
